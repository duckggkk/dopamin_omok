package com.dopamin.omok.user.adapter.out.persistence;

import com.dopamin.omok.user.domain.User;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import com.dopamin.omok.config.JpaAuditingConfig;
import org.springframework.boot.test.autoconfigure.orm.jpa.DataJpaTest;
import org.springframework.context.annotation.Import;

import java.util.Optional;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;

@DataJpaTest
@Import(JpaAuditingConfig.class)
class UserPersistenceAdapterTest {

    @Autowired UserJpaRepository userJpaRepository;

    private UserPersistenceAdapter adapter;

    @BeforeEach
    void setUp() {
        adapter = new UserPersistenceAdapter(userJpaRepository);
    }

    private User savedUser(String email, String nickname) {
        return adapter.save(User.createLocalUser(email, "encodedPass1!", nickname));
    }

    @Test
    @DisplayName("유저 저장 후 ID로 조회")
    void save_and_findById() {
        User saved = savedUser("a@test.com", "nickA");

        Optional<User> found = adapter.findById(saved.getId());

        assertThat(found).isPresent();
        assertThat(found.get().getEmail()).isEqualTo("a@test.com");
    }

    @Test
    @DisplayName("이메일로 유저 조회")
    void findByEmail_found() {
        savedUser("b@test.com", "nickB");

        Optional<User> found = adapter.findByEmail("b@test.com");

        assertThat(found).isPresent();
        assertThat(found.get().getNickname()).isEqualTo("nickB");
    }

    @Test
    @DisplayName("존재하지 않는 이메일은 빈 Optional")
    void findByEmail_notFound() {
        assertThat(adapter.findByEmail("none@test.com")).isEmpty();
    }

    @Test
    @DisplayName("publicId로 유저 조회")
    void findByPublicId_found() {
        User saved = savedUser("c@test.com", "nickC");
        UUID publicId = saved.getPublicId();

        Optional<User> found = adapter.findByPublicId(publicId);

        assertThat(found).isPresent();
        assertThat(found.get().getEmail()).isEqualTo("c@test.com");
    }

    @Test
    @DisplayName("존재하지 않는 publicId는 빈 Optional")
    void findByPublicId_notFound() {
        assertThat(adapter.findByPublicId(UUID.randomUUID())).isEmpty();
    }

    @Test
    @DisplayName("이메일 중복 여부 확인")
    void existsByEmail() {
        savedUser("dup@test.com", "nickDup");

        assertThat(adapter.existsByEmail("dup@test.com")).isTrue();
        assertThat(adapter.existsByEmail("other@test.com")).isFalse();
    }

    @Test
    @DisplayName("닉네임 중복 여부 확인")
    void existsByNickname() {
        savedUser("d@test.com", "uniqueNick");

        assertThat(adapter.existsByNickname("uniqueNick")).isTrue();
        assertThat(adapter.existsByNickname("other")).isFalse();
    }

    @Test
    @DisplayName("publicId는 저장 시 자동 생성")
    void save_publicIdAutoGenerated() {
        User saved = savedUser("e@test.com", "nickE");

        assertThat(saved.getPublicId()).isNotNull();
    }
}
